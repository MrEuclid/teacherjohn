  <h2>Prime numbers</h2>
</div></div>

<div class = "row">
<div class = "col-sm-6 ">
  <p id = "words">
    A  prime number is one that when divided by an integer greater then 1 there is always a remainder.
    <br>
    <strong>Example is 5 a prime number?</strong>
    <br>
    5 $ \div 2 $ = 2 + 1 remainder  <br>
    5 $ \div 3 $ = 2 + 2 remainder <br>
    5 $ \div 4 $ = 2 + 3 remainder 
    <br> 
    5 is a is a prime number.
</p>
</div>
    <div class = "col-sm-6 ">
      <p>
<strong>Example is 15 a prime number?</strong>
    15 $ \div 2  $ = 7 + 1 remainder <br>
    15 $ \div 3 $ = 5 + 0 remainder <br>
    15 is not a prime number, it has <strong>factors</strong> of 3 and 5. 15 = 3 $ \times 3 $
    <br>
  </p>
</div></div>

