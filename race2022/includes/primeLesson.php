<h2>How to test if a number n is prime</h2>
<p><strong>Divide the number of by all the prime numbers less than or equal to $ \sqrt{n} $. </strong></p>
</div></div>

  <div class = "row">
<div class = "col-sm-6 ">
<strong>Example</strong>
Is 57 a prime number?
<br>
$ \sqrt{57} = 7.55 $, divide 57 by 2,3,5,7 to test it.
<br>
 $ 57 \div 2  $= 28 + 1 remainder,  $ 57 \div 3 $= 19 + 0 remainder. $ Therefore 3 is a factor of 57 so 57 is not prime.
 <br>
